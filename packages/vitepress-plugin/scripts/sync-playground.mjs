#!/usr/bin/env node
/**
 * Regenerates the playground's synced pages + `.vitepress/config.mjs` from a sibling `yjs-docs`
 * checkout's real `openspec/` content. Run before `vitepress dev`/`vitepress build` — unlike
 * rspress's virtual `addPages` hook, vitepress routing is file-based, so there's no way to skip
 * this step (see `write-pages.ts`'s header comment).
 */
import {existsSync, mkdirSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createDiskContentSource, readRepoContentOnce} from '@luhanxin/spec-hub-core';
import {writeSpecHubVitepressPages} from '../dist/index.js';

const packageDir = dirname(dirname(fileURLToPath(import.meta.url)));
const yjsDocsOpenspecDir = join(packageDir, '../../../yjs-docs/openspec');
const docsRoot = join(packageDir, 'playground/docs');

async function main() {
  if (!existsSync(yjsDocsOpenspecDir)) {
    console.error(`yjs-docs not found as a sibling directory (expected at ${yjsDocsOpenspecDir}).`);
    process.exit(1);
  }

  const source = createDiskContentSource(yjsDocsOpenspecDir);
  const repoContent = await readRepoContentOnce(source, {org: 'lhx-space', repo: 'yjs-docs'});
  console.log(
    `Synced ${repoContent.capabilities.length} capabilities, ${repoContent.archivedChanges.length} archived changes from yjs-docs.`
  );

  const {sidebar} = await writeSpecHubVitepressPages({repos: [repoContent], docsRoot});

  mkdirSync(join(docsRoot, '.vitepress'), {recursive: true});
  writeFileSync(
    join(docsRoot, '.vitepress', 'config.mjs'),
    [
      '// Generated by scripts/sync-playground.mjs — do not edit by hand, re-run the script instead.',
      'export default {',
      "  title: 'lhx-spec-hub playground (vitepress)',",
      `  description: 'Live preview of writeSpecHubVitepressPages rendering ${repoContent.capabilities.length} capabilities from yjs-docs',`,
      `  themeConfig: {sidebar: ${JSON.stringify(sidebar, null, 2)}}`,
      '};',
      ''
    ].join('\n')
  );

  console.log(`Wrote playground pages + sidebar config under ${docsRoot}`);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
